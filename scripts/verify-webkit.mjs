import assert from 'node:assert/strict';
import { webkit } from 'playwright';

const browser = await webkit.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
await page.goto(process.env.TEST_URL || 'http://localhost:5173');
await page.getByRole('button', { name: 'Mais de 99999' }).click();
await page.locator('.hero').waitFor();
await page.waitForFunction(() => !document.querySelector('audio').paused && document.querySelector('audio').currentTime > 0);
await page.waitForTimeout(2700);
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
await page.locator('.hero').screenshot({ path: 'test-results/hero-webkit.png' });
await page.getByRole('tab', { name: /A platinada/ }).click();
await page.getByRole('tabpanel').getByText('Você sabia, né?').waitFor();
await page.getByRole('button', { name: /Ampliar foto: Você, edição de capa/ }).click();
await page.getByRole('dialog').waitFor();
await page.getByRole('button', { name: 'Fechar foto' }).click();
await page.locator('#conversas').getByRole('button', { name: 'Dar play na nossa conversa', exact: true }).click();
await page.waitForFunction(() => { const video = document.querySelector('#conversas video'); return video.currentTime > 0 && !video.paused; });
assert.equal(await page.locator('#conversas video').evaluate((video) => video.muted), true);
assert.equal(await page.locator('audio').evaluate((audio) => audio.paused), false);
await page.locator('#conversas').getByRole('button', { name: 'Rever nossa conversa', exact: true }).waitFor();
await page.getByRole('button', { name: /TOQUE PARA ABRIR/ }).click();
await page.getByLabel('Senha da carta', { exact: true }).fill('Amoe');
await page.getByRole('button', { name: 'Desbloquear minha carta' }).click();
await page.locator('.letter-paper').waitFor();
assert.deepEqual(errors, []);
await browser.close();
console.log('OK: WebKit mobile — pergunta, áudio, versões, galeria, vídeo, carta e largura. Nenhum erro JavaScript.');
